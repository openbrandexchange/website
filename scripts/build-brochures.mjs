#!/usr/bin/env node
// Render the brochures (public/downloads/{brands,retailers}-<lang>.pdf) and the social preview
// images (public/og/<lang>.jpg) for all 25 languages with headless Chrome.
//
//   npm run build:brochures                 # everything
//   npm run build:brochures -- --lang el,bg # only these languages
//   CHROME_PATH=/path/to/chrome npm run build:brochures
//
// Uses the installed Google Chrome (macOS default path below), else Playwright's Chromium.
// Fails when any page overflows its A4 sheet, so a longer translation never gets cut off.
// Writes public/downloads/manifest.json with an input hash per file; `npm test` fails when a
// text changed but the PDFs were not rebuilt.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';
import { langs } from '../src/lib/i18n-core.ts';
import { brandsHtml, inputsHash, ogHtml, retailersHtml, rootPath } from './brochure/template.mjs';

const MAC_CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const executablePath = process.env.CHROME_PATH || (existsSync(MAC_CHROME) ? MAC_CHROME : undefined);

const arg = (name) => {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
};
const only = arg('--lang')?.split(',');
const targets = only ? langs.filter((l) => only.includes(l)) : langs;

const downloads = `${rootPath}public/downloads/`;
const og = `${rootPath}public/og/`;
const cache = `${rootPath}.cache/brochures/`;
for (const dir of [downloads, og, cache]) mkdirSync(dir, { recursive: true });

const manifestPath = `${downloads}manifest.json`;
const manifest = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, 'utf8')) : { files: {} };

const browser = await chromium.launch({ executablePath, headless: true });
const context = await browser.newContext();
const problems = [];

async function render(name, html, write) {
  const file = `${cache}${name}.html`;
  writeFileSync(file, html);
  const page = await context.newPage();
  await page.goto('file://' + file, { waitUntil: 'load' });
  await page.evaluate(() => document.fonts.ready);
  await write(page);
  await page.close();
}

async function pdf(kind, lang, html) {
  const name = `${kind}-${lang}`;
  await render(name, html, async (page) => {
    await page.emulateMedia({ media: 'print' });
    // A page whose content is taller than the sheet would be clipped: refuse to write it.
    const overflow = await page.evaluate(() =>
      [...document.querySelectorAll('.page')].flatMap((p, i) => {
        const limit = p.getBoundingClientRect().bottom - parseFloat(getComputedStyle(p).paddingBottom) + 2;
        const inFlow = [...p.children].filter((c) => getComputedStyle(c).position !== 'absolute');
        // On the cover the flow diagram sits at the bottom: the text above must end before it.
        const flow = p.querySelector('.flow');
        const limit2 = flow ? flow.getBoundingClientRect().top - 8 : limit;
        const worst = Math.max(...inFlow.map((c) => c.getBoundingClientRect().bottom)) - (flow ? limit2 - limit : 0);
        return worst > limit || p.scrollHeight > p.clientHeight + 1 ? [`page ${i + 1} by ${Math.round(worst - limit)}px`] : [];
      }),
    );
    if (overflow.length) problems.push(`${name}: content overflows ${overflow.join(', ')}`);
    const pages = await page.evaluate(() => document.querySelectorAll('.page').length);
    await page.pdf({ path: `${downloads}${name}.pdf`, format: 'A4', printBackground: true, preferCSSPageSize: true, tagged: true, outline: false });
    manifest.files[`${name}.pdf`] = { hash: inputsHash(kind, lang), pages };
  });
  console.log('wrote', `public/downloads/${name}.pdf`);
}

async function png(lang) {
  await render(`og-${lang}`, ogHtml(lang), async (page) => {
    await page.setViewportSize({ width: 1200, height: 630 });
    const overflow = await page.evaluate(() => document.body.scrollHeight > 630 || document.querySelector('h1').getBoundingClientRect().top < 120);
    if (overflow) problems.push(`og-${lang}: title does not fit`);
    await page.screenshot({ path: `${og}${lang}.jpg`, type: 'jpeg', quality: 86 });
    manifest.files[`og/${lang}.jpg`] = { hash: inputsHash('og', lang) };
  });
  console.log('wrote', `public/og/${lang}.jpg`);
}

for (const lang of targets) {
  await pdf('brands', lang, brandsHtml(lang));
  await pdf('retailers', lang, retailersHtml(lang));
  await png(lang);
}
await browser.close();

manifest.note = 'Generated by scripts/build-brochures.mjs; tests compare the hashes with the current texts.';
manifest.files = Object.fromEntries(Object.entries(manifest.files).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');

if (problems.length) {
  console.error('\n' + problems.join('\n'));
  process.exit(1);
}
