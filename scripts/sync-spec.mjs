#!/usr/bin/env node
// Copy what the website serves from the specification (spec repository, CC-BY-4.0):
//   - site/ (the rendered API reference, OpenAPI bundles, schemas)  -> public/reference/
//   - site/schemas/                                                 -> public/schemas/
//     (so the schemas' $id, https://openbrandexchange.com/schemas/v0.1/…, resolves)
//   - the error table of docs/protocol.md                           -> src/data/errors.json
//     (the pages at /errors/<obx_error>, the `type` of every problem+json answer)
//   npm run sync:spec                 # expects ../spec next to this repo
//   npm run sync:spec -- <path-to-spec-checkout>
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';

const here = (p) => new URL(p, import.meta.url).pathname;
const spec = process.argv[2] ?? here('../../spec');
if (!existsSync(join(spec, 'site', 'protocol.html')) || !existsSync(join(spec, 'docs', 'protocol.md'))) {
  console.error(`No spec checkout with site/ at ${spec}. Pass the path to a checkout of openbrandexchange/spec.`);
  process.exit(1);
}

const reference = here('../public/reference');
const schemas = here('../public/schemas');
rmSync(reference, { recursive: true, force: true });
rmSync(schemas, { recursive: true, force: true });
cpSync(join(spec, 'site'), reference, { recursive: true, filter: (src) => !src.endsWith('README.md') });
cpSync(join(spec, 'site', 'schemas'), schemas, { recursive: true });

// Rows like: | `validation_failed` | 422 | body is well-formed but invalid; see `errors[]` |
const doc = readFileSync(join(spec, 'docs', 'protocol.md'), 'utf8');
const table = doc.slice(doc.indexOf('| `obx_error` | HTTP | Meaning |'));
const errors = [];
for (const line of table.split('\n').slice(2)) {
  const m = /^\| `([a-z_]+)` \| ([0-9/]+) \| (.+) \|$/.exec(line.trim());
  if (!m) break;
  errors.push({ code: m[1], status: m[2], meaning: m[3].trim() });
}
const known = JSON.parse(readFileSync(join(spec, 'schemas', 'Common.json'), 'utf8')).$defs.ErrorCode.enum;
const missing = known.filter((c) => !errors.some((e) => e.code === c));
if (errors.length < 20 || missing.length) {
  console.error(`The error table in docs/protocol.md has ${errors.length} codes; missing: ${missing.join(', ') || 'none'}.`);
  process.exit(1);
}
let commit = 'unknown';
try {
  commit = execFileSync('git', ['-C', spec, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
} catch {
  // not a git checkout
}
writeFileSync(
  here('../src/data/errors.json'),
  JSON.stringify({ $comment: 'Generated by npm run sync:spec from spec/docs/protocol.md. Do not edit.', spec_commit: commit, errors }, null, 2) + '\n',
);
console.log(`Copied the reference and schemas of spec ${commit.slice(0, 7)}; ${errors.length} error codes in src/data/errors.json.`);
