#!/usr/bin/env node
// Copy what the website serves from the specification (spec repository, CC-BY-4.0):
//   - site/ (the rendered API reference, OpenAPI bundles, schemas)  -> public/reference/
//   - site/schemas/v<major.minor>/ (every version, the frozen older ones included)
//                                                                   -> public/schemas/
//     (so each schema's $id, https://openbrandexchange.com/schemas/v0.2/…, resolves)
//   - the error table of docs/protocol.md and the label completeness warnings of
//     docs/import-format.md (rule 10)                               -> src/data/errors.json
//     (the pages at /errors/<code>, the `type` of every problem+json answer)
//   npm run sync:spec                 # expects ../spec next to this repo
//   npm run sync:spec -- <path-to-spec-checkout>
import { cpSync, existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';

const here = (p) => new URL(p, import.meta.url).pathname;
const spec = process.argv[2] ?? here('../../spec');
if (!existsSync(join(spec, 'site', 'protocol.html')) || !existsSync(join(spec, 'docs', 'protocol.md'))) {
  console.error(`No spec checkout with site/ at ${spec}. Pass the path to a checkout of openbrandexchange/spec.`);
  process.exit(1);
}

const reference = here('../public/reference');
const schemas = here('../public/schemas');
rmSync(reference, { recursive: true, force: true });
rmSync(schemas, { recursive: true, force: true });
cpSync(join(spec, 'site'), reference, { recursive: true, filter: (src) => !src.endsWith('README.md') });
cpSync(join(spec, 'site', 'schemas'), schemas, { recursive: true });
const versions = readdirSync(schemas).filter((d) => /^v\d+\.\d+$/.test(d)).sort();
const current = JSON.parse(readFileSync(join(spec, 'schemas', 'Common.json'), 'utf8')).$id.match(/\/schemas\/(v\d+\.\d+)\//)?.[1];
if (!current || !versions.includes(current)) {
  console.error(`site/schemas/ has ${versions.join(', ') || 'no versions'}, but the current schemas are ${current ?? 'unversioned'}. Run npm run build:site in the spec first.`);
  process.exit(1);
}

// Rows like: | `validation_failed` | 422 | body is well-formed but invalid; see `errors[]` |
const doc = readFileSync(join(spec, 'docs', 'protocol.md'), 'utf8');
const table = doc.slice(doc.indexOf('| `obx_error` | HTTP | Meaning |'));
const errors = [];
for (const line of table.split('\n').slice(2)) {
  const m = /^\| `([a-z_]+)` \| ([0-9/]+) \| (.+) \|$/.exec(line.trim());
  if (!m) break;
  errors.push({ code: m[1], status: m[2], meaning: m[3].trim() });
}
const known = JSON.parse(readFileSync(join(spec, 'schemas', 'Common.json'), 'utf8')).$defs.ErrorCode.enum;
const missing = known.filter((c) => !errors.some((e) => e.code === c));
if (errors.length < 20 || missing.length) {
  console.error(`The error table in docs/protocol.md has ${errors.length} codes; missing: ${missing.join(', ') || 'none'}.`);
  process.exit(1);
}
// Label completeness warnings (import-format.md rule 10), rows like:
// | `fibre_composition_missing` | a textile item type without `materials` | `materials` | the fibre ... |
const imp = readFileSync(join(spec, 'docs', 'import-format.md'), 'utf8');
const wtable = imp.slice(imp.indexOf('| Code | When | Column | Why (legal basis) |'));
const warnings = [];
for (const line of wtable.split('\n').slice(2)) {
  const m = /^\| `([a-z0-9_]+)` \| (.+?) \| `([a-z_]+)` \| (.+) \|$/.exec(line.trim());
  if (!m) break;
  warnings.push({ code: m[1], when: m[2].trim(), column: m[3], why: m[4].trim() });
}
const knownWarnings = JSON.parse(readFileSync(join(spec, 'schemas', 'Common.json'), 'utf8')).$defs.WarningCode?.enum ?? [];
const missingWarnings = knownWarnings.filter((c) => !warnings.some((w) => w.code === c));
if (missingWarnings.length || warnings.length !== knownWarnings.length) {
  console.error(`The warning table in docs/import-format.md has ${warnings.length} codes; missing: ${missingWarnings.join(', ') || 'none'}.`);
  process.exit(1);
}
let commit = 'unknown';
try {
  commit = execFileSync('git', ['-C', spec, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
} catch {
  // not a git checkout
}
writeFileSync(
  here('../src/data/errors.json'),
  JSON.stringify(
    {
      $comment: 'Generated by npm run sync:spec from spec/docs/protocol.md (errors) and spec/docs/import-format.md rule 10 (warnings). Do not edit.',
      spec_commit: commit,
      schema_versions: versions,
      current_schema_version: current,
      errors,
      warnings,
    },
    null,
    2,
  ) + '\n',
);
console.log(
  `Copied the reference and schemas (${versions.join(', ')}) of spec ${commit.slice(0, 7)}; ${errors.length} error codes and ${warnings.length} warning codes in src/data/errors.json.`,
);
