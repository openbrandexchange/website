#!/usr/bin/env node
// Copy the project glossary into src/data/: the terms from admin-ui (its source of truth,
// admin-ui/src/i18n/glossary.json) and the publisher line per language from the spec
// (spec/docs/glossary.md, "The project and its publisher"). The locale tests check the site's
// words against these copies.
//   npm run sync:glossary                 # expects ../admin-ui and ../spec next to this repo
//   npm run sync:glossary -- <glossary.json> <glossary.md>
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';

const here = (p) => new URL(p, import.meta.url).pathname;
const json = process.argv[2] ?? here('../../admin-ui/src/i18n/glossary.json');
const md = process.argv[3] ?? here('../../spec/docs/glossary.md');
for (const f of [json, md]) {
  if (!existsSync(f)) {
    console.error(`Not found: ${f}. Pass the paths to admin-ui/src/i18n/glossary.json and spec/docs/glossary.md.`);
    process.exit(1);
  }
}
copyFileSync(json, here('../src/data/glossary.json'));

// Rows like: | Deutsch (`de`) | (in Gründung) | Eine Initiative von |
const section = readFileSync(md, 'utf8').split('## The project and its publisher')[1]?.split('\n## ')[0] ?? '';
const publisher = {};
for (const m of section.matchAll(/^\|[^|]*\(`([a-z]{2})`\)\s*\|\s*\(([^)]+)\)\s*\|\s*([^|]+?)\s*\|$/gm)) {
  publisher[m[1]] = { inFormation: m[2].trim(), initiative: m[3].trim() };
}
if (Object.keys(publisher).length !== 25) {
  console.error(`Expected 25 languages in the publisher table of ${md}, found ${Object.keys(publisher).length}.`);
  process.exit(1);
}
writeFileSync(
  here('../src/data/glossary-publisher.json'),
  JSON.stringify({ $comment: 'Generated by npm run sync:glossary from spec/docs/glossary.md. Do not edit.', languages: publisher }, null, 2) + '\n',
);
console.log('Updated src/data/glossary.json and src/data/glossary-publisher.json. Run npm test to see which texts disagree.');
